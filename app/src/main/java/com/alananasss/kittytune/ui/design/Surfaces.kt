/**
 * Central entry points for surfaces and cards.
 *
 * Container backgrounds intentionally stay Material: the Liquid Glass treatment is reserved for
 * controls (buttons, switches, sliders, chips, fields...), so lists and pages keep the theme's real
 * surface colours. The wrappers remain here so call sites do not each decide their own style.
 */
@Composable
fun Surface(
    modifier: Modifier = Modifier,
    shape: Shape = RectangleShape,
    color: Color = MaterialTheme.colorScheme.surface,
    contentColor: Color = contentColorFor(color),
    tonalElevation: Dp = 0.dp,
    shadowElevation: Dp = 0.dp,
    border: BorderStroke? = null,
    content: @Composable () -> Unit,
) {
    MaterialSurface(
        modifier = modifier,
        shape = shape,
        color = color,
        contentColor = contentColor,
        tonalElevation = tonalElevation,
        shadowElevation = shadowElevation,
        border = border,
        content = content
    )
}

